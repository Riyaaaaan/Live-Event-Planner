/**
 * Generates public/firebase-messaging-sw.js from .env (VITE_FIREBASE_*).
 * Run before build so background push uses the same config as the app.
 */
import { readFileSync, writeFileSync, existsSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const envPath = join(root, '.env')

let env = {}
if (existsSync(envPath)) {
  readFileSync(envPath, 'utf8').split('\n').forEach((line) => {
    const m = line.match(/^([^#=]+)=(.*)$/)
    if (m) env[m[1].trim()] = m[2].trim().replace(/^["']|["']$/g, '')
  })
}

const get = (k) => env[k] || ''

const config = {
  apiKey: get('VITE_FIREBASE_API_KEY'),
  authDomain: get('VITE_FIREBASE_AUTH_DOMAIN'),
  projectId: get('VITE_FIREBASE_PROJECT_ID'),
  storageBucket: get('VITE_FIREBASE_STORAGE_BUCKET'),
  messagingSenderId: get('VITE_FIREBASE_MESSAGING_SENDER_ID'),
  appId: get('VITE_FIREBASE_APP_ID'),
}

const content = `// Generated by scripts/generate-firebase-sw.js - do not edit by hand
const firebaseConfig = ${JSON.stringify(config, null, 2)};
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');
firebase.initializeApp(firebaseConfig);
const messaging = firebase.messaging();
messaging.onBackgroundMessage(function(payload) {
  const title = (payload.notification && payload.notification.title) || 'Notification';
  const options = {
    body: (payload.notification && payload.notification.body) || '',
    icon: '/favicon.svg',
    tag: payload.data && payload.data.tag ? payload.data.tag : undefined,
    data: payload.data || {},
  };
  return self.registration.showNotification(title, options);
});
`

writeFileSync(join(root, 'public', 'firebase-messaging-sw.js'), content, 'utf8')
console.log('[generate-firebase-sw] Wrote public/firebase-messaging-sw.js')
